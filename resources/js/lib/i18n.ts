export function normalizeLocale(locale: string): Locale {
    return locale === 'ar' || locale === 'fr' ? locale : 'en';
}

export function createTranslator(locale: string) {
    const dictionary = messages[normalizeLocale(locale) as Exclude<Locale, 'en'>];

    return (key: string): string => dictionary?.[key] ?? key;
}

export function roleLabel(role: string, translate: (key: string) => string): string {
    const key = role.replaceAll('_', ' ').replace(/\b\w/g, (letter) => letter.toUpperCase());

    return translate(key);
}
