L.Icon.Default.mergeOptions({
    iconRetinaUrl: markerIcon2x,
    iconUrl: markerIcon,
    shadowUrl: markerShadow,
});

export const DEFAULT_MAP_CENTER: [number, number] = [33.8938, 35.5018];
export const DEFAULT_MAP_ZOOM = 13;

export default L;
